import esphome.codegen as cg
import esphome.config_validation as cv
from esphome.core import ID
from esphome.cpp_generator import RawExpression

from ..display import CONF_INIT_SEQUENCE_ID
from . import EpaperModel

# Sentinel for the display_mode config key
CONF_DISPLAY_MODE = "display_mode"

DISPLAY_MODES = {
    "full": RawExpression("esphome::epaper_spi::SSD1683DisplayMode::FULL"),
    "partial": RawExpression("esphome::epaper_spi::SSD1683DisplayMode::PARTIAL"),
    "grayscale4": RawExpression("esphome::epaper_spi::SSD1683DisplayMode::GRAYSCALE4"),
    "fast": RawExpression("esphome::epaper_spi::SSD1683DisplayMode::FAST"),
}


class SSD1683Model(EpaperModel):
    """
    Model class for SSD1683 e-paper displays.

    Accepts a 233-byte grayscale LUT used in GRAYSCALE4 display mode.
    Also supports a ``display_mode`` config option.
    """

    def __init__(self, name, gray_lut, class_name="EPaperSSD1683", **defaults):
        super().__init__(name, class_name, **defaults)
        self.gray_lut = gray_lut

    def get_extra_schema(self):
        return {
            cv.Optional(CONF_DISPLAY_MODE, default="full"): cv.one_of(
                *DISPLAY_MODES, lower=True
            ),
        }

    def get_constructor_args(self, config) -> tuple:
        # Embed the 233-byte grayscale LUT as a static const array
        lut = cg.static_const_array(
            ID(config[CONF_INIT_SEQUENCE_ID].id + "_gray_lut", type=cg.uint8),
            self.gray_lut,
        )
        return lut, len(self.gray_lut)

    async def to_code(self, var, config):
        mode = config.get(CONF_DISPLAY_MODE, "full")
        cg.add(var.set_display_mode(DISPLAY_MODES[mode]))


